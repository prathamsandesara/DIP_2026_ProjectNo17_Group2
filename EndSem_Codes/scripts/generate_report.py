def readme_block() -> str:
    p3, p4 = jload("phase3_integration_benchmark"), jload("phase4_categorization_benchmark")
    S = p3["benchmark_summary"]
    s1, s4 = S[0], S[3]
    c4 = s4["confusion_matrix"]
    lat = jload("latency_profile")
    return (
        "| Test split (81 rolls) | Stage 1 baseline | Full pipeline |\n| --- | --- | --- |\n"
        f"| Accuracy | {s1['screening_accuracy_pct']}% | **{s4['screening_accuracy_pct']}%** |\n"
        f"| Recall | {s1['recall_sensitivity_pct']}% | **{s4['recall_sensitivity_pct']}%** ({c4['tp']}/{c4['tp'] + c4['fn']}) |\n"
        f"| Specificity | {s1['specificity_pct']}% | **{s4['specificity_pct']}%** ({c4['tn']}/{c4['tn'] + c4['fp']}) |\n"
        f"| Pooled Dice | {s1['pooled_dice_defective_pct']}% | **{s4['pooled_dice_defective_pct']}%** |\n"
        f"| Taxonomy (oracle / end-to-end) | – | {p4['oracle_diagnostic_accuracy_pct']}% / {p4['cascaded_end_to_end_accuracy_pct']}% |\n"
        f"| Compute per roll (single thread) | – | {lat['stages']['total_measured_roll_ms']:.0f} ms |\n"
    )


def main() -> None:
    Path("docs").mkdir(exist_ok=True)
    Path("docs/REPORT.md").write_text(build())
