def cload(name):
    return list(csv.DictReader(open(T / f"{name}.csv")))


def wilson(k, n, z=1.96):
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    s = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return 100 * (c - s), 100 * (c + s)


def ci(k, n):
    lo, hi = wilson(k, n)
    return f"{100 * k / n:.2f}% [{lo:.1f}, {hi:.1f}]"


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join(" --- " for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def csv_table(rows, drop=()):
    if not rows:
        return ""
    cols = [c for c in rows[0].keys() if c not in drop]
    return table(cols, [[r[c] for c in cols] for r in rows])


